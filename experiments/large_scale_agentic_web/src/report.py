def _verdict(ok, partial=False):
    return "**MET**" if ok else ("**PARTIALLY MET**" if partial else "**NOT MET**")


def sec_success(L, summary):
    """Evaluate the pre-registered success criteria against the measured data."""
    A = L.append
    main_n = summary["main_n"]
    scales = sorted(summary.get("scales", []))
    A("## Success criteria")
    A("")
    A("The experiment was specified with three criteria. They are evaluated here against the "
      "measured numbers, independently of whether the proposed architecture comes out ahead.")
    A("")

    # --- SCALE: does the effect persist at N >= 1e4 ---------------------------
    big = [n for n in scales if n >= 10_000]
    rows = []
    for n in scales:
        t_acc = find_test(summary, n, TARGETED, "accuracy_macro", "B6", "B3")
        t_iss = find_test(summary, n, TARGETED, "iss", "B6", "B3")
        t_gq = find_test(summary, n, CORRELATED, "accuracy_macro", "B7", "B6")
        if not t_acc:
            continue
        rows.append({"N": f"{n:,}", "B6−B3 accuracy": t_acc["mean_diff"],
                     "Holm p": p_str(t_acc["p_holm"]),
                     "B6−B3 ISS": t_iss["mean_diff"] if t_iss else float("nan"),
                     "B7−B6 accuracy (G_Q)": t_gq["mean_diff"] if t_gq else float("nan"),
                     "seeds": t_acc["n_pairs"]})
    scale_ok = bool(big) and all(
        (find_test(summary, n, TARGETED, "accuracy_macro", "B6", "B3") or {}).get("mean_diff", 0) > 0
        and (find_test(summary, n, TARGETED, "iss", "B6", "B3") or {}).get("mean_diff", 0) > 0
        for n in big)
    A(f"### 1. SCALE — does the behaviour persist at N ≥ 10⁴? {_verdict(scale_ok)}")
    A("")
    A(md_table(rows, ["N", "B6−B3 accuracy", "Holm p", "B6−B3 ISS",
                      "B7−B6 accuracy (G_Q)", "seeds"]))
    A("")

    # --- RESILIENCE: KS advantage under correlated / targeted failure ---------
    res_rows = []
    for cond in (CORRELATED, DOMAIN70, TARGETED):
        for b in ("B3", "B5"):
            t = find_test(summary, main_n, cond, "knowledge_survival", "B6", b)
            if t:
                res_rows.append({"condition": cond, "comparison": f"B6 − {b}",
                                 "ΔKS": t["mean_diff"], "d_z": t["cohens_dz"],
                                 "Holm p": p_str(t["p_holm"]),
                                 "significant": "yes" if t["significant_holm_05"] else "no"})
    pos = [r for r in res_rows if r["ΔKS"] > 0 and r["significant"] == "yes"]
    res_ok = len(pos) == len(res_rows) and bool(res_rows)
    res_partial = bool(pos) and not res_ok
    A(f"### 2. RESILIENCE — KS(lineage) > KS(replication) at comparable budget under "
      f"correlated or targeted failure? {_verdict(res_ok, res_partial)}")
    A("")
    A(md_table(res_rows, ["condition", "comparison", "ΔKS", "d_z", "Holm p", "significant"]))
    A("")
    A(f"{len(pos)} of {len(res_rows)} equal-budget survival comparisons are positive and "
      f"significant. Where they are not, the correct reading is that at matched storage the "
      f"three policies keep roughly the same *amount* of knowledge alive; what differs is whether "
      f"what survives is independent, and whether the answer built from it is correct.")
    A("")

    # --- DISCOVERY: G_Q > 0 --------------------------------------------------
    gq_rows = []
    for cond in (CORRELATED, TARGETED, ROOTCORR, PARTITION):
        for metric, label in (("acc_revision_sensitive", "stale-fact accuracy"),
                              ("contradiction_resolved_acc", "contradiction resolution"),
                              ("accuracy_macro", "downstream accuracy")):
            t = find_test(summary, main_n, cond, metric, "B7", "B6")
            if t:
                gq_rows.append({"condition": cond, "metric": label, "G_Q": t["mean_diff"],
                                "d_z": t["cohens_dz"], "Holm p": p_str(t["p_holm"]),
                                "significant": "yes" if t["significant_holm_05"] else "no"})
    disc_pos = [r for r in gq_rows if r["G_Q"] > 0 and r["significant"] == "yes"]
    disc_ok = bool(gq_rows) and len(disc_pos) == len(gq_rows)
    A(f"### 3. DISCOVERY — does continual questioning produce a statistically meaningful "
      f"improvement? {_verdict(disc_ok, bool(disc_pos))}")
    A("")
    A(md_table(gq_rows, ["condition", "metric", "G_Q", "d_z", "Holm p", "significant"]))
    A("")
    t_ctrl = find_test(summary, main_n, CORRELATED, "accuracy_macro", "B3Q", "B3")
    t_gq = find_test(summary, main_n, CORRELATED, "accuracy_macro", "B7", "B6")
    if t_ctrl and t_gq:
        bigger = "larger" if t_ctrl["mean_diff"] > t_gq["mean_diff"] else "smaller"
        A(f"**Important qualification.** The identical questioning machinery applied to a "
          f"count-based system gains {signed(t_ctrl['mean_diff'])} accuracy, which is {bigger} "
          f"than the {signed(t_gq['mean_diff'])} it gains on top of lineage. Criterion 3 is "
          f"therefore met for continual discovery as a mechanism, but the data do **not** support "
          f"the stronger claim that questioning depends on, or is amplified by, lineage awareness.")
    A("")
    return L


def sec_limits(L, summary):
    A = L.append
    A("## Limitations")
    A("")
    A("1. **No LLM calls anywhere.** Semantic reasoning is abstracted: a claim's value is a "
      "symbol and an answer is correct iff it equals the claim's current true value. Nothing here "
      "measures whether an agent can formulate a good question in natural language, extract "
      "evidence from text, or recognise that two differently-worded claims are the same claim. "
      "Every result is a claim about the *distribution layer*, not about end-to-end agents. This "
      "was both a scope decision (the hypothesis is about evidence topology under failure) and an "
      "environment constraint (no model credentials were available on the machine that ran this).")
    A("2. **Simulation artefacts.** Placement, failure and retrieval are modelled, not deployed. "
      "The retrieval model assumes all live agents are mutually reachable outside the partition "
      "regime, which is a *conservative* assumption for the hypothesis: it maximises the value of "
      "having a replica anywhere at all, which favours the broad-replication baselines.")
    A("3. **Re-verification is modelled as a privileged operation, and that inflates G_Q.** "
      "A REVERIFY question contacts the claim's origin, and the origin re-observes the world, so "
      "unless that origin is corrupt the refreshed value is correct by construction. Most of the "
      "measured questioning gain is therefore a measurement of *what re-verification is worth if "
      "you can do it*, at a stated message price — not evidence that formulating good questions is "
      "itself easy or cheap. The informative parts of the questioning ablation are the ones that "
      "are not tautological: that ADD_SUPPORT (publishing an additional independent origin — the "
      "genuinely lineage-flavoured question) contributes far less than re-verification, that "
      "returns saturate and then waste messages, that fragility-based targeting is not the best "
      "targeting policy, and that the same gain appears without lineage.")
    A("4. **Contradiction ground truth is world-level**: a claim counts as contradictory if the "
      "evidence that exists anywhere in the world disagrees, including evidence no system stores. "
      "This is system-independent by design, but it caps the achievable recall of every "
      "small-budget policy and flatters broad replication, which probes far more of that evidence.")
    A("5. **Recovery time is a logical-round proxy**, not wall-clock latency.")
    A("6. **The white-box attacker is greedy and batched** (8 recomputation rounds), so it is a "
      "lower bound on an optimal adversary.")
    A("7. **The scaling trends come from the measured scales only.** They are reported as empirical "
      "trends with log-log slopes and R², never as asymptotic complexity.")
    A("8. **One world generator.** All results are conditional on the generative model of the "
      "world (heavy-tailed family sizes, ~35% single-origin claims, 25% revised facts, "
      "locality-correlated homes). The parameters are declared in `configs/` and can be swept.")
    A("")
    return L


