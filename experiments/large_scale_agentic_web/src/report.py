    A("![scaling](figures/fig3_scaling.png)")
    A("")
    pts = summary.get("scaling_points", {})
    if "B6" in pts and len(pts["B6"]) >= 2:
        first, last = pts["B6"][0], pts["B6"][-1]
        A(f"For the lineage fabric, per-claim storage is fixed by the budget k and therefore does "
          f"not grow with N ({num(first['storage_per_claim'], 2)} at N = {first['n_agents']:,} → "
          f"{num(last['storage_per_claim'], 2)} at N = {last['n_agents']:,}); retrieval cost is "
          f"{num(first['mean_probe_rounds'], 2)} → {num(last['mean_probe_rounds'], 2)} rounds, and "
          f"knowledge survival is {num(first['knowledge_survival'])} → "
          f"{num(last['knowledge_survival'])}. The behaviour therefore persists at N ≥ 10⁴; "
          f"the total knowledge base grows with N (2 claims per agent), so per-claim costs that stay "
          f"flat mean total system cost grows linearly in N rather than super-linearly.")
    A("")
    return L


