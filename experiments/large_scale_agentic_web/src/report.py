def sec_partition(L, summary):
    A = L.append
    main_n = summary["main_n"]
    A("## Partition and reconciliation result")
    A("")
    A("The network is split into 2 or 4 components; facts are updated independently inside the "
      "component that holds their origin; then the network reconnects. `acc_updated` is the "
      "reconciliation rate — of the claims updated during the split, the fraction that carry the "
      "post-update value afterwards. `conflict_visible` is the fraction of those claims where the "
      "system can actually *see* the disagreement in the evidence it retrieves.")
    A("")
    rows = []
    for s_ in ("B0", "B1", "B2", "B3", "B4", "B5", "B6", "B7", "B3Q"):
        v = t1(summary, PARTITION, s_, "KS")
        if isinstance(v, float) and math.isnan(v):
            continue
        rows.append({"system": s_, "KS": v, "accuracy": t1(summary, PARTITION, s_, "accuracy"),
                     "acc_updated": t1(summary, PARTITION, s_, "acc_partition_updated"),
                     "conflict_visible": t1(summary, PARTITION, s_, "conflict_visible_rate"),
                     "contradiction_F1": t1(summary, PARTITION, s_, "contradiction_F1")})
    A(md_table(rows, ["system", "KS", "accuracy", "acc_updated", "conflict_visible",
                      "contradiction_F1"],
               ["sys", "KS", "accuracy", "reconciliation rate", "conflict visible", "contr. F1"]))
    A("")
    for a, b in (("B6", "B3"), ("B7", "B6"), ("B7", "B3Q")):
        t = find_test(summary, main_n, PARTITION, "accuracy_macro", a, b)
        if t:
            A(f"- After reconnection, {a} − {b} accuracy {test_phrase(t)}")
    A("")
    return L


