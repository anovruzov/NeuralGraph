def num(x, nd=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{x:.{nd}f}"


def signed(x, nd=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{x:+.{nd}f}"


def p_str(p):
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "n/a"
    return "<1e-6" if p < 1e-6 else f"{p:.2g}"


def t1(summary, condition, system, field):
    for r in summary.get("table1", []):
        if r["condition"] == condition and r["system"] == system:
            return r.get(field, float("nan"))
    return float("nan")


def find_test(summary, n_agents, condition, metric, a, b):
    for t in summary.get("tests", []):
        if (t["n_agents"] == n_agents and t["condition"] == condition
                and t["metric"] == metric and t["system_a"] == a and t["system_b"] == b):
            return t
    return None


def test_phrase(t, nd=3):
    if not t:
        return "no paired data"
    return (f"Δ = {signed(t['mean_diff'], nd)} "
            f"(95% CI [{num(t['ci_low'], nd)}, {num(t['ci_high'], nd)}], "
            f"d_z = {num(t['cohens_dz'], 2)}, paired t p = {p_str(t['p_paired_t'])}, "
            f"Holm p = {p_str(t['p_holm'])}, n = {t['n_pairs']})")


def md_table(rows, cols, headers=None, nd=3):
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        cells = []
        for c in cols:
            v = r.get(c)
            if isinstance(v, float):
                cells.append("--" if math.isnan(v) else f"{v:.{nd}f}")
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def direction(d, up="higher", down="lower", flat="indistinguishable"):
    if d is None or (isinstance(d, float) and math.isnan(d)):
        return "n/a"
    if abs(d) < 1e-9:
        return flat
    return up if d > 0 else down


