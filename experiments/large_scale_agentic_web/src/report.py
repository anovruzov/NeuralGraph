      "`tables/table2_statistical_tests.csv`. Every comparison is paired by seed — the same world, "
      "workload and failure draw is given to both systems — and reports the mean difference, a "
      "bootstrap 95% CI of that difference (10,000 resamples), Cohen's d_z, a paired t-test, a "
